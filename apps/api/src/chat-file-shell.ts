// Guest scripts for the chat file browser. They run with the path in argv, not interpolated,
// and they refuse a path whose real parent is outside this bot's folder or shared/.

function script(lines: readonly string[]): string {
  return lines.join("\n");
}

/** Resolves each component and exits 2 when the real path leaves the allowed prefixes. */
export const LIVE_PATH_CONTAINMENT_SCRIPT = script([
  "set -eu",
  "root=$(pwd -P)",
  "rel=$1",
  "shift",
  "current=$root",
  "rest=$rel",
  'while [ -n "$rest" ]; do',
  "  IFS=/ read -r part rest <<ENDPATH",
  "$rest",
  "ENDPATH",
  "  case $part in",
  '    "" | . | ..) exit 2 ;;',
  "  esac",
  "  next=$current/$part",
  '  if [ ! -e "$next" ] && [ ! -L "$next" ]; then',
  "    break",
  "  fi",
  '  if [ -d "$next" ]; then',
  '    current=$(cd -P -- "$next" && pwd) || exit 2',
  "  else",
  "    target=$next",
  "    hops=0",
  '    while [ -L "$target" ]; do',
  '      link=$(readlink "$target") || exit 2',
  "      case $link in",
  "        /*) target=$link ;;",
  '        *) target=$(dirname "$target")/$link ;;',
  "      esac",
  "      hops=$((hops + 1))",
  '      [ "$hops" -le 32 ] || exit 2',
  "    done",
  '    parent=$(dirname "$target")',
  '    name=$(basename "$target")',
  '    parent=$(cd -P -- "$parent" && pwd) || exit 2',
  "    current=$parent/$name",
  '    if [ -n "$rest" ]; then',
  "      exit 2",
  "    fi",
  "  fi",
  "  case $current in",
  '    "$root"|"$root"/*) ;;',
  "    *) exit 2 ;;",
  "  esac",
  "done",
  "ok=0",
  'for prefix in "$@"; do',
  '  if [ "$prefix" = "." ]; then',
  "    allowed=$root",
  "  else",
  "    allowed=$root/$prefix",
  "  fi",
  "  case $current in",
  '    "$allowed"|"$allowed"/*) ok=1 ;;',
  "  esac",
  "done",
  '[ "$ok" = 1 ] || exit 2',
  "exit 0",
]);

/** Writes one base64 chunk to a new /tmp file and prints that path. */
export const LIVE_STAGE_SCRIPT = script([
  "set -eu",
  "tmp=$(mktemp /tmp/rakazo-save.XXXXXX)",
  'if ! printf \'%s\' "$1" | base64 -d > "$tmp" 2>/dev/null; then',
  '  printf \'%s\' "$1" | base64 -D > "$tmp"',
  "fi",
  "printf '%s' \"$tmp\"",
]);

/** Appends one base64 chunk to the staged /tmp file. */
export const LIVE_APPEND_SCRIPT = script([
  "set -eu",
  "case $1 in",
  "  /tmp/rakazo-save.[A-Za-z0-9]*) ;;",
  "  *) exit 1 ;;",
  "esac",
  'if ! printf \'%s\' "$2" | base64 -d >> "$1" 2>/dev/null; then',
  '  printf \'%s\' "$2" | base64 -D >> "$1"',
  "fi",
]);

/**
 * Copies the staged file into the workspace without following a symlink.
 * Exits 2 when a parent or the final name would leave the allowed prefixes.
 */
export const LIVE_COMMIT_SCRIPT = script([
  "set -eu",
  "tmp=$1",
  "rel=$2",
  "shift 2",
  "case $tmp in",
  "  /tmp/rakazo-save.[A-Za-z0-9]*) ;;",
  "  *) exit 1 ;;",
  "esac",
  "root=$(pwd -P)",
  'cleanup() { rm -f -- "$tmp"; }',
  "trap cleanup EXIT",
  'name=$(basename -- "$rel")',
  'parent=$(dirname -- "$rel")',
  'if [ "$parent" = "." ]; then',
  "  parent=",
  "fi",
  "case $name in",
  '  "" | . | ..) exit 2 ;;',
  "esac",
  "under_root() {",
  "  current=$1",
  "  case $current in",
  '    "$root"|"$root"/*) return 0 ;;',
  "    *) return 1 ;;",
  "  esac",
  "}",
  "allowed_dir() {",
  "  current=$(pwd -P)",
  '  under_root "$current" || return 1',
  '  for prefix in "$@"; do',
  '    if [ "$prefix" = "." ]; then',
  "      return 0",
  "    fi",
  "    allowed=$root/$prefix",
  "    case $current in",
  '      "$allowed"|"$allowed"/*) return 0 ;;',
  "    esac",
  "  done",
  "  return 1",
  "}",
  'cd -P -- "$root"',
  "rest=$parent",
  'while [ -n "$rest" ]; do',
  "  IFS=/ read -r part rest <<ENDPATH",
  "$rest",
  "ENDPATH",
  "  case $part in",
  '    "" | . | ..) exit 2 ;;',
  "  esac",
  '  if [ -L "$part" ]; then',
  "    exit 2",
  "  fi",
  '  if [ -d "$part" ]; then',
  '    cd -P -- "$part"',
  '    under_root "$(pwd -P)" || exit 2',
  '  elif [ ! -e "$part" ]; then',
  '    allowed_dir "$@" || exit 2',
  '    mkdir -- "$part"',
  '    cd -P -- "$part"',
  '    under_root "$(pwd -P)" || exit 2',
  "  else",
  "    exit 2",
  "  fi",
  "done",
  'allowed_dir "$@" || exit 2',
  'if [ -L "$name" ] || [ -d "$name" ]; then',
  "  exit 2",
  "fi",
  "perl -e '",
  "use Fcntl qw(O_WRONLY O_CREAT O_TRUNC O_NOFOLLOW);",
  "my ($src, $dest) = @ARGV;",
  'open(my $in, "<", $src) or die $!;',
  "binmode($in);",
  "sysopen(my $out, $dest, O_WRONLY|O_CREAT|O_TRUNC|O_NOFOLLOW, 0600) or die $!;",
  "binmode($out);",
  "while (1) {",
  "  my $n = read($in, my $buf, 65536);",
  "  die $! unless defined $n;",
  "  last if $n == 0;",
  "  print $out $buf or die $!;",
  "}",
  "close($out) or die $!;",
  "close($in);",
  '\' -- "$tmp" "$name"',
  "trap - EXIT",
  'rm -f -- "$tmp"',
]);
